package io.github.egorka2000.tf2mc.movement;

/**
 * То, что циклу подшагов {@link SubstepLoop} нужно от игрока: скорость, перемещение со столкновениями,
 * опора под ногами и направление взгляда.
 *
 * <p>Классы игры здесь не используются. В игре интерфейс реализует {@link Tf2Travel} поверх игрока
 * Minecraft, в юнит-тестах — подставной игрок. Все величины в единицах и осях Minecraft:
 * блоки, блоки за тик, вверх направлена y.
 */
public interface MovingBody {
	/** Скорость по x, блоков за тик. */
	double velocityX();

	/** Скорость вверх, блоков за тик. */
	double velocityY();

	/** Скорость по z, блоков за тик. */
	double velocityZ();

	/** Записывает скорость, блоков за тик. */
	void setVelocity(double x, double y, double z);

	/**
	 * Перемещает игрока на заданное смещение с учётом столкновений.
	 *
	 * <p>Как штатное перемещение игры: при столкновении обнуляет соответствующую составляющую
	 * скорости и обновляет признак опоры.
	 */
	void move(double dx, double dy, double dz);

	/** Стоит ли игрок на опоре по итогам последнего перемещения. */
	boolean onGround();

	/** Угол поворота взгляда, градусы. */
	double yawDegrees();
}
